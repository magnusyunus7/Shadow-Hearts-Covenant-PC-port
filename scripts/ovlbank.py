"""Package one PS2Recomp overlay output directory as an overlay *bank* for the runtime.

Every overlay of Shadow Hearts: Covenant is loaded at the same address, so the generated functions
of FIELD, BATTLE and OPENING have identical names (sub_0045EAC0_... etc.). This script:
  * copies each generated function file to DEST as zz_ovl_<NAME>_<file>.cpp, with its body wrapped in
    `namespace shc_ovl_<NAME> { ... }` and the shared header include swapped for a per-overlay one;
  * writes zz_ovl_<NAME>_functions.h (the namespaced declarations);
  * writes zz_ovl_<NAME>_bank.cpp, which rebuilds the overlay's dense function table at start-up from
    run-length records and registers it with ps2x_overlay::registerBank(). The bank is selected at
    run time by the overlay header in guest RAM ("MWo3" magic + overlay id at the load address).

Usage: python ovlbank.py OUT_DIR NAME OVERLAY.BIN DEST_DIR
       (OVERLAY.BIN = "-" makes an always-active supplement bank for main-executable functions)
  e.g. python ovlbank.py ov2/out_BATTLE BATTLE BATTLE.BIN C:/shc/port/ps2xRuntime/src/runner
"""
import os, re, struct, sys

out_dir, name, ovl_path, dest = sys.argv[1:5]
ns = f"shc_ovl_{name}"
if ovl_path == '-':
    # Supplement bank for the MAIN executable: always active, consulted only when the main
    # function table has no entry for an address.
    magic, oid, load_addr = b'\0\0\0\0', 0, 0
else:
    hdr = open(ovl_path, 'rb').read(0x40)
    magic, oid, load_addr = struct.unpack_from('<4sII', hdr, 0)
    assert magic == b'MWo3', f"{ovl_path} is not an MWo3 overlay"

# Remove any previous bank files for this overlay so stale functions do not linger.
prefix = f"zz_ovl_{name}_"
for f in os.listdir(dest):
    if f.startswith(prefix):
        os.remove(os.path.join(dest, f))

# Functions defined in this bank (one per generated .cpp).
local_defs = set()
for f in os.listdir(out_dir):
    if f.endswith('.cpp') and f != 'register_functions.cpp':
        m0 = re.search(r'^void (\w+)\(uint8_t\* rdram', open(os.path.join(out_dir, f), encoding='utf-8', errors='surrogateescape').read(), re.M)
        if m0:
            local_defs.add(m0.group(1))
supplement = (ovl_path == '-')
call_re = re.compile(r'(?<![\w:])((?:sub|entry)_\w+)\((?=rdram\b)')
def qualify(m):
    name = m.group(1)
    if name in local_defs:
        return f"{ns}::{name}("
    # A direct call to a function that is not part of this bank: it lives in the main executable.
    return f"::{name}("

# --- function files -----------------------------------------------------------------------------
count = 0
for f in sorted(os.listdir(out_dir)):
    if not f.endswith('.cpp') or f == 'register_functions.cpp':
        continue
    src = open(os.path.join(out_dir, f), encoding='utf-8', errors='surrogateescape').read()
    if supplement:
        src = src.replace('#include <ps2_recompiled_functions.h>',
                          f'#include <ps2_recompiled_functions.h>\n#include "zz_ovl_{name}_functions.h"')
    else:
        src = src.replace('#include <ps2_recompiled_functions.h>', f'#include "zz_ovl_{name}_functions.h"')
    m = re.search(r'^// Function:', src, re.M) or re.search(r'^void ', src, re.M)
    if not m:
        raise SystemExit(f"cannot find function start in {f}")
    body = call_re.sub(qualify, src[m.start():])
    src = src[:m.start()] + f"namespace {ns} {{\n\n" + body + f"\n}} // namespace {ns}\n"
    open(os.path.join(dest, prefix + f), 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write(src)
    count += 1

# --- header ---------------------------------------------------------------------------------------
decls = re.findall(r'^void (\w+)\(uint8_t\* rdram, R5900Context\* ctx, PS2Runtime \*runtime\);',
                   open(os.path.join(out_dir, 'ps2_recompiled_functions.h')).read(), re.M)
with open(os.path.join(dest, f"zz_ovl_{name}_functions.h"), 'w', newline='\n') as h:
    h.write(f"#pragma once\n// Generated by ovlbank.py: {name} overlay (id {oid}) function declarations.\n")
    h.write("#include <cstdint>\nstruct R5900Context;\nclass PS2Runtime;\n\n")
    h.write(f"namespace {ns} {{\n")
    for d in decls:
        if d not in local_defs:
            continue
        h.write(f"void {d}(uint8_t* rdram, R5900Context* ctx, PS2Runtime *runtime);\n")
    h.write(f"}} // namespace {ns}\n")

# --- bank registration ---------------------------------------------------------------------------------
reg = open(os.path.join(out_dir, 'register_functions.cpp')).read()
base = int(re.search(r'g_ps2RecompiledFunctionTableBase = (0x[0-9a-fA-F]+)u', reg).group(1), 16)
slots = int(re.search(r'g_ps2RecompiledFunctionTableSlotCount = (\d+)u', reg).group(1))
assign = sorted((int(s), fn) for s, fn in re.findall(r'g_ps2RecompiledFunctionTable\[(\d+)\] = (\w+);', reg))
funcs = sorted({fn for _, fn in assign})
missing = set(funcs) - set(decls)
if missing:
    raise SystemExit(f"table references undeclared functions: {sorted(missing)[:5]}")
index = {fn: i for i, fn in enumerate(funcs)}
runs = []
for s, fn in assign:
    i = index[fn]
    if runs and runs[-1][2] == i and runs[-1][0] + runs[-1][1] == s:
        runs[-1][1] += 1
    else:
        runs.append([s, 1, i])

with open(os.path.join(dest, f"zz_ovl_{name}_bank.cpp"), 'w', newline='\n') as c:
    c.write(f"// Generated by ovlbank.py: function bank for the {name} overlay (MWo3 id {oid}, load 0x{load_addr:X}).\n")
    c.write('#include "runtime/ps2_overlay_banks.h"\n')
    c.write(f'#include "zz_ovl_{name}_functions.h"\n\n')
    c.write(f"namespace {ns} {{\nnamespace {{\n")
    c.write(f"constexpr uint32_t kSlotCount = {slots}u;\n")
    c.write(f"PS2Runtime::RecompiledFunction g_table[kSlotCount] = {{}};\n")
    c.write("const PS2Runtime::RecompiledFunction kFunctions[] = {\n")
    for fn in funcs:
        c.write(f"    {fn},\n")
    c.write("};\nconst ps2x_overlay::Run kRuns[] = {\n")
    for r in runs:
        c.write(f"    {{{r[0]}u, {r[1]}u, {r[2]}u}},\n")
    c.write("};\n")
    c.write("struct BankRegistration {\n    BankRegistration() {\n")
    c.write("        ps2x_overlay::buildTable(g_table, kSlotCount, kFunctions, kRuns, sizeof(kRuns) / sizeof(kRuns[0]));\n")
    c.write("        ps2x_overlay::Bank bank;\n")
    c.write(f'        bank.name = "{name}";\n')
    c.write(f"        bank.signatureAddr = 0x{load_addr:X}u;\n")
    c.write(f"        bank.signature0 = 0x{struct.unpack('<I', magic)[0]:08X}u; // 'MWo3'\n")
    c.write(f"        bank.signature1 = {oid}u; // overlay id\n")
    c.write(f"        bank.tableBase = 0x{base:X}u;\n")
    c.write("        bank.slotCount = kSlotCount;\n")
    c.write("        bank.table = g_table;\n")
    c.write("        ps2x_overlay::registerBank(bank);\n    }\n};\n")
    c.write("const BankRegistration g_registration;\n")
    c.write(f"}} // namespace\n}} // namespace {ns}\n")

print(f"{name}: id={oid} load=0x{load_addr:X} table=0x{base:X}+{slots} slots, "
      f"{count} function files, {len(funcs)} functions, {len(runs)} runs -> {dest}")
